export function isLang(value: unknown): value is Lang {
  return LANGS.some((lang) => lang.id === value)
}

export function detectLang(): Lang {
  const tag = navigator.language.toLowerCase()
  if (tag.startsWith('zh')) {
    if (tag.includes('tw') || tag.includes('hk') || tag.includes('hant')) return 'zh-TW'
    return 'zh-CN'
  }
  if (tag.startsWith('ja')) return 'ja'
  if (tag.startsWith('es')) return 'es'
  return 'en'
}

export function translate(lang: Lang, key: CopyKey, vars?: Record<string, string | number>): string {
  let text = dictionaries[lang][key] ?? dictionaries.en[key]
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value))
    }
  }
  return text
}

